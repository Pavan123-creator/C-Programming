#include <stdio.h>

int main()
{
    // x,y,z and ch are variables
    // int, float, double, char are data types
    // double provides more precision than float
    int x = 2;
    float y = 98.123456f;
    double z = 98.123456;
    char ch = 'A';
    printf("Integer: %d\n", x);
    printf("Float: %f\n", y);
    printf("Double: %lf\n", z);
    printf("Character: %c\n", ch);

    return 0;
}